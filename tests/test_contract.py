"""The parcel contract's checks, run over every normalised sample."""

from datetime import date, datetime
from zoneinfo import ZoneInfo

import pytest

from custom_components.amazon_orders.account.parcels import (
    is_pickup,
    normalize_parcel,
    planned_for_status,
    planned_window,
)
from custom_components.amazon_orders.const import ParcelStatus

from .payloads import active_record, delivered_record, in_transit_record

CANONICAL_KEYS = [
    "carrier",
    "barcode",
    "sender",
    "receiver",
    "status",
    "raw_status",
    "delivered",
    "delivered_at",
    "planned_from",
    "planned_to",
    "pickup",
    "pickup_point",
    "url",
    "weight",
    "dimensions",
    "history",
    "raw",
]

_AMS = ZoneInfo("Europe/Amsterdam")


def _windowed(record, start, end):
    record["delivery_window"] = [start, end]
    return record


SAMPLES = {
    "active": lambda: _windowed(
        active_record(), "2099-10-03T13:00:00+02:00", "2099-10-03T15:00:00+02:00"
    ),
    "in_transit": in_transit_record,
    "delivered": lambda: _windowed(
        delivered_record(), "2099-10-03T13:00:00+02:00", "2099-10-03T15:00:00+02:00"
    ),
}


@pytest.fixture(params=SAMPLES)
def parcel(request) -> dict:
    return normalize_parcel(SAMPLES[request.param]())


def test_keys_and_order(parcel):
    assert list(parcel) == CANONICAL_KEYS


def test_delivered_follows_status(parcel):
    assert parcel["delivered"] is (parcel["status"] is ParcelStatus.DELIVERED)


def test_delivered_at_only_when_delivered(parcel):
    if not parcel["delivered"]:
        assert parcel["delivered_at"] is None


def test_planned_window_is_ordered_and_anchored(parcel):
    if parcel["planned_to"] is not None:
        assert parcel["planned_from"] is not None
        assert datetime.fromisoformat(parcel["planned_to"]) > datetime.fromisoformat(
            parcel["planned_from"]
        )


def test_planned_is_empty_once_delivered(parcel):
    if parcel["delivered"]:
        assert parcel["planned_from"] is None
        assert parcel["planned_to"] is None


def test_pickup_is_false_without_a_pickup_status(parcel):
    assert parcel["pickup"] is False
    assert parcel["pickup_point"] is None


def test_pickup_follows_a_pickup_point_timeline_event(monkeypatch):
    monkeypatch.setattr(
        "custom_components.amazon_orders.account.parcels.map_event_status",
        lambda message: ParcelStatus.AT_PICKUP_POINT if message == "ready" else None,
    )
    record = in_transit_record()
    record["events"] = [{"timestamp": "2026-04-29T10:00:00Z", "message": "ready"}]
    parcel = normalize_parcel(record)
    assert parcel["pickup"] is True
    assert parcel["pickup_point"] is None


def test_a_predicted_window_keeps_both_ends():
    parcel = normalize_parcel(SAMPLES["active"]())
    assert parcel["planned_from"] == "2099-10-03T13:00:00+02:00"
    assert parcel["planned_to"] == "2099-10-03T15:00:00+02:00"


